import fs from 'node:fs/promises';

const SOURCE_URL = 'https://raw.githubusercontent.com/bacinger/f1-circuits/master/f1-circuits.geojson';
const OUTPUT_URL = new URL('../src/track-layouts.generated.js', import.meta.url);
const SAMPLE_COUNT = 112;
const TARGET_SPAN = 430;

const TRACK_IDS = {
  monza: 'it-1922',
  spa: 'be-1925',
  silverstone: 'gb-1948',
  nurburgring: 'de-1927',
  suzuka: 'jp-1962',
  imola: 'it-1953',
  redbull: 'at-1969',
};

function closedPolylineSample(points, count) {
  const closed = [...points, points[0]];
  const lengths = [0];
  for (let i = 1; i < closed.length; i++) {
    const [ax, az] = closed[i - 1];
    const [bx, bz] = closed[i];
    lengths.push(lengths.at(-1) + Math.hypot(bx - ax, bz - az));
  }
  const total = lengths.at(-1);
  return Array.from({ length: count }, (_, sampleIndex) => {
    const distance = total * sampleIndex / count;
    let segment = 1;
    while (segment < lengths.length - 1 && lengths[segment] < distance) segment++;
    const startDistance = lengths[segment - 1];
    const endDistance = lengths[segment];
    const alpha = (distance - startDistance) / Math.max(1e-9, endDistance - startDistance);
    const [ax, az] = closed[segment - 1];
    const [bx, bz] = closed[segment];
    return [ax + (bx - ax) * alpha, az + (bz - az) * alpha];
  });
}

function elevationFor(key, t) {
  if (key === 'spa') return 19 + Math.sin(t * Math.PI * 2 - .8) * 15 + Math.sin(t * Math.PI * 4 + .6) * 5;
  if (key === 'nurburgring') return 11 + Math.sin(t * Math.PI * 2 + .5) * 8 + Math.sin(t * Math.PI * 6) * 2.5;
  if (key === 'silverstone') return 2 + Math.sin(t * Math.PI * 2) * 1.5;
  if (key === 'suzuka') return 8 + Math.sin(t * Math.PI * 2 - .4) * 5 + Math.sin(t * Math.PI * 6 + .7) * 2;
  if (key === 'imola') return 12 + Math.sin(t * Math.PI * 2 + .9) * 9 + Math.sin(t * Math.PI * 8) * 2;
  if (key === 'redbull') return 24 + Math.sin(t * Math.PI * 2 - .5) * 12 + Math.sin(t * Math.PI * 4) * 3;
  return 1.5 + Math.sin(t * Math.PI * 2 + .3) * 1.2;
}

function normalizeTrack(key, coordinates) {
  const unique = coordinates.slice(0, -1);
  const meanLat = unique.reduce((sum, point) => sum + point[1], 0) / unique.length;
  const cosLat = Math.cos(meanLat * Math.PI / 180);
  const projected = unique.map(([longitude, latitude]) => [longitude * 111320 * cosLat, latitude * 110540]);
  const minX = Math.min(...projected.map((point) => point[0]));
  const maxX = Math.max(...projected.map((point) => point[0]));
  const minZ = Math.min(...projected.map((point) => point[1]));
  const maxZ = Math.max(...projected.map((point) => point[1]));
  const centerX = (minX + maxX) / 2;
  const centerZ = (minZ + maxZ) / 2;
  const scale = TARGET_SPAN / Math.max(maxX - minX, maxZ - minZ);
  const centered = projected.map(([x, z]) => [(x - centerX) * scale, (z - centerZ) * scale]);
  return closedPolylineSample(centered, SAMPLE_COUNT).map(([x, z], index) => [
    Number(x.toFixed(3)),
    Number(z.toFixed(3)),
    Number(elevationFor(key, index / SAMPLE_COUNT).toFixed(3)),
  ]);
}

const response = await fetch(SOURCE_URL);
if (!response.ok) throw new Error(`Unable to download F1 circuit data: HTTP ${response.status}`);
const geojson = await response.json();
const layouts = {};
for (const [key, id] of Object.entries(TRACK_IDS)) {
  const feature = geojson.features.find((candidate) => candidate.properties?.id === id);
  if (!feature || feature.geometry?.type !== 'LineString') throw new Error(`Circuit not found: ${id}`);
  layouts[key] = normalizeTrack(key, feature.geometry.coordinates);
}

const banner = `// Generated by tools/import-f1-circuits.mjs. Do not hand-edit.\n// Source: bacinger/f1-circuits (MIT), https://github.com/bacinger/f1-circuits\n`;
await fs.writeFile(OUTPUT_URL, `${banner}export const TRACK_LAYOUTS = ${JSON.stringify(layouts, null, 2)};\n`);
console.log(`Wrote ${OUTPUT_URL.pathname}: ${Object.keys(layouts).length} circuits × ${SAMPLE_COUNT} points`);
